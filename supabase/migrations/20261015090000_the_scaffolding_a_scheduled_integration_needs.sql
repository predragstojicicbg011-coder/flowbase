-- What a scheduled integration needs, and nothing more.
--
-- `20261008130000_remove_subscription_and_processor_features` dropped the
-- whole processor apparatus with Chargebee and Braintree, correctly: a
-- construction company has no subscriptions and no card processor. But it also
-- took the four small things that ANY scheduled integration rests on — somewhere
-- to keep a credential, somewhere to keep a job's configuration, a record of
-- what each run did, and the function that cron calls.
--
-- SEF is the first of those integrations: the tax administration's e-invoice
-- service, which every company in Serbia receives its supplier bills through.
-- This brings back the four, sized for that and not for what was removed.
--
-- WHAT IS DELIBERATELY DIFFERENT FROM THE APPLICATION THIS CAME FROM:
--
--   * The function base url is read from `job_config.functions_base_url`. It
--     used to be derived by rewriting the last path segment of a key named
--     after Chargebee, which no longer means anything here and which hid what
--     the value actually was.
--   * `job_config` gets row level security and NO permissive policy. It holds
--     the service role key, which is not a thing any signed-in account should
--     be able to read. Only the service role reaches it, and that bypasses RLS.
--   * `integration_credentials` holds an API key, so it is the administrator's
--     alone — not every member's.
--
-- Every table here takes the restrictive `members_only` policy that
-- `20261010090000` requires of new tables, on top of whatever it allows.

begin;

-- ── Extensions ────────────────────────────────────────────────────────────
--
-- Both ship with Supabase. Named here so a database that somehow lacks one
-- fails on this line, with its name, rather than three objects later on a
-- message about a missing schema.

create extension if not exists pg_cron with schema extensions;
create extension if not exists pg_net with schema extensions;

-- ── Where a credential lives ──────────────────────────────────────────────

create table if not exists public.integration_credentials (
  id          uuid primary key default gen_random_uuid(),
  provider    text not null,
  site        text,
  api_key     text,
  api_secret  text,
  merchant_id text,
  extra       jsonb,
  is_active   boolean default true,
  created_at  timestamptz default now(),
  updated_at  timestamptz default now()
);

comment on table public.integration_credentials is
  'API keys for outside services, one row per provider. Holds secrets: the '
  'administrator reads it, and the edge functions reach it as service_role.';

alter table public.integration_credentials enable row level security;
alter table public.integration_credentials force row level security;

create policy members_only on public.integration_credentials as restrictive
  for all to authenticated
  using (public.is_member()) with check (public.is_member());

create policy integration_credentials_admin on public.integration_credentials
  for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- ── A job's configuration ─────────────────────────────────────────────────
--
-- Holds the service role key, so it is readable by NOBODY through PostgREST.
-- RLS with no permissive policy means every signed-in read comes back empty,
-- which is the intended answer rather than an oversight. The functions that
-- need it are granted `execute` on `run_processor_sync`, which is security
-- definer and reads it on their behalf.

create table if not exists public.job_config (
  key   text primary key,
  value text not null,
  note  text
);

comment on table public.job_config is
  'Configuration for scheduled jobs. Secret: RLS is on and there is no '
  'permissive policy, so only the service role and security-definer '
  'functions can read it.';

alter table public.job_config enable row level security;
alter table public.job_config force row level security;

create policy members_only on public.job_config as restrictive
  for all to authenticated
  using (public.is_member()) with check (public.is_member());

-- ── What each run did ─────────────────────────────────────────────────────

create table if not exists public.processor_sync_runs (
  id           bigint generated by default as identity primary key,
  sync_date    date not null,
  provider     text not null,
  account      text not null default '',
  status       text not null default 'running'
                 check (status in ('running', 'complete', 'failed')),
  started_at   timestamptz not null default now(),
  finished_at  timestamptz,
  period_from  date,
  period_to    date,
  transactions integer,
  error        text,
  export_id    text,
  unique (sync_date, provider, account)
);

comment on table public.processor_sync_runs is
  'One row per provider per day, reclaimed on every pass — a state, not a '
  'history. Read by the screen that says when the last pull was.';

alter table public.processor_sync_runs enable row level security;
alter table public.processor_sync_runs force row level security;

create policy members_only on public.processor_sync_runs as restrictive
  for all to authenticated
  using (public.is_member()) with check (public.is_member());

-- Read-only to members: the inbox shows when it last ran and why it failed.
-- Written only by the service role, which bypasses RLS.
create policy processor_sync_runs_read on public.processor_sync_runs
  for select to authenticated using (public.is_member());

create table if not exists public.scheduled_job_runs (
  id            bigint generated by default as identity primary key,
  job           text not null,
  fired_at      timestamptz not null default now(),
  belgrade_at   timestamptz not null,
  belgrade_hour integer not null,
  would_run     boolean not null,
  note          text
);

comment on table public.scheduled_job_runs is
  'The trace cron leaves: what fired, at what hour in Belgrade, and whether '
  'it went on to call anything. The first place to look when a job is silent.';

alter table public.scheduled_job_runs enable row level security;
alter table public.scheduled_job_runs force row level security;

create policy members_only on public.scheduled_job_runs as restrictive
  for all to authenticated
  using (public.is_member()) with check (public.is_member());

create policy scheduled_job_runs_read on public.scheduled_job_runs
  for select to authenticated using (public.is_member());

-- ── Claiming a run ────────────────────────────────────────────────────────
--
-- One row per provider per day. A pass that finds a run already `running` and
-- not yet stale takes nothing and returns null, so two passes cannot both
-- think they own the day.

create or replace function public.claim_processor_sync(
  p_date        date,
  p_provider    text,
  p_account     text default '',
  p_stale_after interval default '00:05:00'::interval
) returns bigint
language sql security definer
set search_path to 'public'
as $$
  insert into public.processor_sync_runs
    (sync_date, provider, account, status, started_at,
     finished_at, transactions, error, export_id)
  values (p_date, p_provider, p_account, 'running', clock_timestamp(),
          null, null, null, null)
  on conflict (sync_date, provider, account) do update
     set status       = 'running',
         started_at   = clock_timestamp(),
         finished_at  = null,
         transactions = null,
         error        = null,
         export_id    = null
   where public.processor_sync_runs.status <> 'running'
      or public.processor_sync_runs.started_at < clock_timestamp() - p_stale_after
  returning id;
$$;

revoke all on function public.claim_processor_sync(date, text, text, interval)
  from public, anon;
grant execute on function public.claim_processor_sync(date, text, text, interval)
  to service_role;

-- ── What cron calls ───────────────────────────────────────────────────────
--
-- `pg_net` hands the request off and returns an id rather than waiting, so
-- what came back is in `net._http_response` under that id — which is where to
-- look when a job reports success and nothing happened.
--
-- The hour check is for jobs that must run once a day: cron is scheduled in
-- UTC and Belgrade moves twice a year, so a daily job is scheduled at BOTH
-- hours that can be 07:00 Belgrade and the wrong one is refused here. A job
-- that runs through the day passes `force`.

create or replace function public.run_processor_sync(
  p_function text,
  force      boolean default false,
  p_body     jsonb   default '{}'::jsonb
) returns text
language plpgsql security definer
set search_path to public, extensions, net
as $fn$
declare
  hour_now int;
  base_url text;
  fn_key   text;
  request  bigint;
  outcome  text;
begin
  hour_now := extract(hour from (now() at time zone 'Europe/Belgrade'))::int;

  if hour_now <> 7 and not force then
    outcome := p_function || ': woke an hour out — the daylight-saving half of the pair';
    insert into public.scheduled_job_runs (job, belgrade_at, belgrade_hour, would_run, note)
    values (p_function, now() at time zone 'Europe/Belgrade', hour_now, false, outcome);
    return outcome;
  end if;

  select value into base_url from public.job_config where key = 'functions_base_url';
  select value into fn_key   from public.job_config where key = 'service_role_key';

  if base_url is null or fn_key is null then
    outcome := p_function || ': job_config has no functions_base_url and/or '
             || 'service_role_key — nothing was called';
    insert into public.scheduled_job_runs (job, belgrade_at, belgrade_hour, would_run, note)
    values (p_function, now() at time zone 'Europe/Belgrade', hour_now, true, outcome);
    return outcome;
  end if;

  select net.http_post(
    url     := rtrim(base_url, '/') || '/' || p_function,
    headers := jsonb_build_object(
                 'Authorization', 'Bearer ' || fn_key,
                 'Content-Type',  'application/json'),
    body    := p_body,
    timeout_milliseconds := 150000
  ) into request;

  outcome := p_function || ': called, pg_net request ' || request
           || case when force and hour_now <> 7
                then ' — FORCED at ' || hour_now || ':00 Belgrade' else '' end;

  insert into public.scheduled_job_runs (job, belgrade_at, belgrade_hour, would_run, note)
  values (p_function, now() at time zone 'Europe/Belgrade', hour_now, true, outcome);

  return outcome;
end
$fn$;

revoke all on function public.run_processor_sync(text, boolean, jsonb) from public, anon;

-- ── The key is checked where it is typed ──────────────────────────────────
--
-- The service role key is pasted in by hand, and a key with a stray space or
-- newline fails with 401 from the gateway and nothing saying why. Checked on
-- the way in, where the mistake is still in front of whoever made it.
--
-- `btrim(x)` with one argument removes SPACES ONLY. The characters that
-- actually arrive on a paste are tabs and newlines, so they are named.

create or replace function public.job_config_clean_key() returns trigger
language plpgsql as $$
begin
  if new.key in ('service_role_key', 'functions_base_url') then
    new.value := btrim(new.value, E' \t\r\n');
    if new.value = '' then
      raise exception '% cannot be empty', new.key
        using errcode = 'invalid_parameter_value';
    end if;
  end if;

  if new.key = 'service_role_key'
     and new.value !~ '^[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+$'
     and new.value !~ '^sb_secret_' then
    raise exception 'service_role_key is neither a JWT nor an sb_secret_ key — '
                    'check what was pasted'
      using errcode = 'invalid_parameter_value';
  end if;

  return new;
end $$;

drop trigger if exists job_config_clean_key on public.job_config;
create trigger job_config_clean_key
  before insert or update on public.job_config
  for each row execute function public.job_config_clean_key();

-- ── Checks ────────────────────────────────────────────────────────────────
--
-- Run against the database this is applied to, so a mistake is a failed
-- migration rather than a job that is quietly inert.

do $$
declare
  saved     text;
  had_saved boolean;
begin
  -- Every table carries the restrictive policy new tables must have.
  if exists (
    select 1 from (values
      ('integration_credentials'), ('job_config'),
      ('processor_sync_runs'), ('scheduled_job_runs')) as t(name)
     where not exists (
       select 1 from pg_policies
        where schemaname = 'public' and tablename = t.name
          and policyname = 'members_only' and permissive = 'RESTRICTIVE')
  ) then
    raise exception 'a new table is missing its members_only policy';
  end if;

  -- anon was closed in 20261008151000 and must not be reopened here.
  if exists (
    select 1 from information_schema.role_table_grants
     where table_schema = 'public' and grantee = 'anon'
       and table_name in ('integration_credentials', 'job_config',
                          'processor_sync_runs', 'scheduled_job_runs')
  ) then
    raise exception 'anon was granted rights on a table it must not reach';
  end if;

  -- The key guard refuses rubbish and keeps a good key intact.
  select value into saved from public.job_config where key = 'service_role_key';
  had_saved := found;

  begin
    insert into public.job_config (key, value) values ('service_role_key', 'not a key')
    on conflict (key) do update set value = excluded.value;
    raise exception 'the key guard let a non-key through';
  exception when invalid_parameter_value then
    null;  -- what should happen
  end;

  insert into public.job_config (key, value)
  values ('service_role_key', E'  aaa.bbb.ccc \n')
  on conflict (key) do update set value = excluded.value;

  if (select value from public.job_config where key = 'service_role_key') <> 'aaa.bbb.ccc' then
    raise exception 'the key guard did not trim what was pasted';
  end if;

  -- Put back exactly what was there, including nothing.
  if had_saved then
    update public.job_config set value = saved where key = 'service_role_key';
  else
    delete from public.job_config where key = 'service_role_key';
  end if;
end $$;

commit;
